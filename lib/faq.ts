/**
 * キーワード一致でFAQ回答を返す（無ければ null）。
 * audience='dealer' の場合は加盟店FAQを優先し、会員向けFAQにもフォールバック。
 */
export function faqMatch(message: string, audience: Audience = 'member'): string | null {
  const m = message.toLowerCase();
  const pool: Faq[] =
    audience === 'dealer'
      ? [...DEALER_FAQS, ...MEMBER_SYSTEM_FAQS, ...FAQS]
      : [...MEMBER_SYSTEM_FAQS, ...FAQS];

  let best: { faq: Faq; score: number } | null = null;
  for (const faq of pool) {
    const score = faq.keywords.reduce((s, k) => (m.includes(k.toLowerCase()) ? s + 1 : s), 0);
    // 先頭（優先セット）のものを活かすため、同点は更新しない
    if (score > 0 && (!best || score > best.score)) best = { faq, score };
  }
  return best ? best.faq.a : null;
}

