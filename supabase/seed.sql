    'admin@demo.example',
    'admin2@demo.example',
    'taro@demo.example',
    'hanako@demo.example',
    'kenji@demo.example',
    'suzuki@demo.example'
  ];
  names  text[] := array[
    '運営事務局',
    'サブ管理者',
    '中古車太郎',
    '花子モータース',
    '購入ケンジ',
    '鈴木オート'
  ];
  i int;
begin
  for i in 1..array_length(ids, 1) loop
    insert into auth.users (
      instance_id, id, aud, role, email, encrypted_password,
      email_confirmed_at, created_at, updated_at,
      raw_app_meta_data, raw_user_meta_data,
      confirmation_token, email_change, email_change_token_new, recovery_token
    ) values (
      '00000000-0000-0000-0000-000000000000',
      ids[i], 'authenticated', 'authenticated',
      emails[i], crypt('password123', gen_salt('bf')),
      now(), now(), now(),
      '{"provider":"email","providers":["email"]}',
      jsonb_build_object('display_name', names[i]),
      '', '', '', ''
    ) on conflict (id) do nothing;

    -- email/password ログイン用 identity
    begin
      insert into auth.identities (
        provider_id, user_id, identity_data, provider,
        last_sign_in_at, created_at, updated_at, id
      ) values (
        ids[i], ids[i],
        jsonb_build_object('sub', ids[i]::text, 'email', emails[i]),
        'email', now(), now(), now(), gen_random_uuid()
      ) on conflict do nothing;
    exception when others then
      raise notice 'identity insert skipped for %: %', emails[i], sqlerrm;
    end;
  end loop;
end $$;

