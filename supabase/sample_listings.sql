create extension if not exists pgcrypto;

-- ---------------------------------------------------------------------------
-- 1) 出品サンプル用の“ログイン不可”ユーザー（管理者ではない / role=user）
-- ---------------------------------------------------------------------------
do $$
declare
  seller_id uuid := 'a0000000-0000-4000-8000-0000000000a1';
begin
  insert into auth.users (
    instance_id, id, aud, role, email, encrypted_password,
    email_confirmed_at, created_at, updated_at,
    raw_app_meta_data, raw_user_meta_data,
    confirmation_token, email_change, email_change_token_new, recovery_token
  ) values (
    '00000000-0000-0000-0000-000000000000',
    seller_id, 'authenticated', 'authenticated',
    'sample-listings@buymo.local',
    -- ランダムで不明なパスワード＝実質ログイン不可（安全）
    crypt(gen_random_uuid()::text || gen_random_uuid()::text, gen_salt('bf')),
    now(), now(), now(),
    '{"provider":"email","providers":["email"]}',
    jsonb_build_object('display_name', 'BUYMO 出品サンプル'),
    '', '', '', ''
  ) on conflict (id) do nothing;

  -- プロフィール（トリガで自動生成されるが、表示名/地域を補完）
  insert into public.profiles (id, display_name, prefecture)
  values (seller_id, 'BUYMO 出品サンプル', '東京都')
  on conflict (id) do update
    set display_name = excluded.display_name,
        prefecture   = excluded.prefecture;
end $$;

