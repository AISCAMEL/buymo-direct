--   安全性: 管理者アカウントは作らない。出品者はログイン不可（ランダムパスワード）。
--   実行:  Supabase Dashboard > SQL Editor に貼り付けて Run（1回だけ）。
--   冪等:  固定UUID + ON CONFLICT DO NOTHING（再実行しても重複しません）。
